//! ST7701S init for the 320x960 bar panel.
//!
//! The panel is configured over a 3-wire (9-bit, CPOL = CPHA = 0) SPI bus, bit-banged through
//! a board-specific [`PanelBus`] (an I2C GPIO expander on the Qualia). Pixels are then streamed
//! over the RGB bus. Init sequence and protocol match Adafruit's CircuitPython
//! `adafruit_qualia.displays.bar320x960` and `dotclockframebuffer.ioexpander_send_init_sequence`.

use embedded_hal::delay::DelayNs;

/// Levels of the panel configuration lines.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct PanelPins {
    pub cs: bool,
    pub sck: bool,
    pub mosi: bool,
    pub reset: bool,
}

/// Something that can drive the panel configuration lines.
pub trait PanelBus {
    type Error;

    /// Set all four lines at once.
    fn write(&mut self, pins: PanelPins) -> Result<(), Self::Error>;
}

/// Bit 7 of the length byte: a delay (in ms, 255 = 500 ms) follows the data.
const DELAY: u8 = 0x80;

