struct Spi<'a, B> {
    bus: &'a mut B,
    pins: PanelPins,
}

impl<B: PanelBus> Spi<'_, B> {
    fn set(&mut self, f: impl FnOnce(&mut PanelPins)) -> Result<(), B::Error> {
        f(&mut self.pins);
        self.bus.write(self.pins)
    }

    fn send(&mut self, is_command: bool, data: &[u8]) -> Result<(), B::Error> {
        let dc: u16 = if is_command { 0 } else { 0x100 };
        for &byte in data {
            let mut bits = byte as u16 | dc;
            for _ in 0..9 {
                // Change data while CLK is low (also asserts CS)...
                let mosi = bits & 0x100 != 0;
                self.set(|p| {
                    p.mosi = mosi;
                    p.sck = false;
                    p.cs = false;
                })?;
                // ...the panel latches on the rising edge.
                self.set(|p| p.sck = true)?;
                bits <<= 1;
            }
        }
        Ok(())
    }
}

/// Reset the panel and send its init sequence.
///
/// Takes a few seconds when `bus` goes through a 100 kHz I2C expander.
pub fn init<B: PanelBus>(bus: &mut B, delay: &mut impl DelayNs) -> Result<(), B::Error> {
    // CS deasserted, CLK idle, panel held in reset.
    let mut spi = Spi {
        bus,
        pins: PanelPins {
            cs: true,
            sck: false,
            mosi: true,
            reset: false,
        },
    };
    spi.set(|_| ())?;
    delay.delay_ms(10);
    spi.set(|p| p.reset = true)?;
    delay.delay_ms(100);

    let mut i = 0;
    while i < INIT_SEQUENCE.len() {
        let cmd = INIT_SEQUENCE[i];
        let len_byte = INIT_SEQUENCE[i + 1];
        let len = (len_byte & !DELAY) as usize;
        let data = &INIT_SEQUENCE[i + 2..i + 2 + len];

        spi.send(true, &[cmd])?;
        spi.send(false, data)?;
        // Idle CLK, then deassert CS.
        spi.set(|p| p.sck = false)?;
        spi.set(|p| p.cs = true)?;

        i += 2 + len;
        if len_byte & DELAY != 0 {
            let ms = match INIT_SEQUENCE[i] {
                255 => 500,
                ms => ms as u32,
            };
            delay.delay_ms(ms);
            i += 1;
        }
    }

    Ok(())
}
